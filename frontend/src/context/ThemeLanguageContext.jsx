export const ThemeLanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => localStorage.getItem('agribridge_lang') || 'en')
  // Theme: strictly 'dark' or 'light' (Forest theme removed as requested)
  const [theme, setThemeState] = useState(() => {
    const saved = localStorage.getItem('agribridge_theme')
    return (saved === 'light') ? 'light' : 'dark'
  })

  useEffect(() => {
    localStorage.setItem('agribridge_lang', language)
    document.documentElement.setAttribute('lang', language)
  }, [language])

  useEffect(() => {
    localStorage.setItem('agribridge_theme', theme)
    document.documentElement.setAttribute('data-theme', theme)
  }, [theme])

  const setLanguage = (lang) => {
    setLanguageState(lang)
  }

  // Toggle strictly between Dark and Light
  const toggleTheme = () => {
    setThemeState((prev) => (prev === 'dark' ? 'light' : 'dark'))
  }

  const setTheme = (thm) => {
    if (thm === 'light' || thm === 'dark') {
      setThemeState(thm)
    }
  }

  const t = (key) => {
    const langDict = TRANSLATIONS[language] || TRANSLATIONS.en
    return langDict[key] || TRANSLATIONS.en[key] || key
  }

  return (
    <ThemeLanguageContext.Provider value={{ language, setLanguage, theme, setTheme, toggleTheme, t }}>
      {children}
    </ThemeLanguageContext.Provider>
  )
}

export const useAppThemeLanguage = () => useContext(ThemeLanguageContext)
